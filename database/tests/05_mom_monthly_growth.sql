SELECT a.*,ROUND(VENTA_NETA_USD-LAG(VENTA_NETA_USD) OVER (ORDER BY FECHA_MES),2) AS VARIACION_USD,
 ROUND(100.0*(VENTA_NETA_USD-LAG(VENTA_NETA_USD) OVER (ORDER BY FECHA_MES))/NULLIF(LAG(VENTA_NETA_USD) OVER (ORDER BY FECHA_MES),0),2) AS VARIACION_MOM_PCT
 FROM (SELECT FECHA_MES,PERIOD_TX,COUNT(DISTINCT CODIGO_TRANSACCION) AS NUM_COMPRAS,COUNT(DISTINCT ID_CLIENTE_OLTP) AS CLIENTES,
 SUM(CANTIDAD) AS UNIDADES,ROUND(SUM(MONTO_NETO_USD),2) AS VENTA_NETA_USD,ROUND(SUM(TOTAL_LINEA_USD),2) AS VENTA_TOTAL_USD,
 ROUND(SUM(COSTO_TOTAL_USD),2) AS COSTO_USD,ROUND(SUM(MARGEN_BRUTO_USD),2) AS UTILIDAD_USD,
 ROUND(SUM(TOTAL_LINEA_USD)/NULLIF(COUNT(DISTINCT CODIGO_TRANSACCION),0),2) AS TICKET_PROMEDIO_USD,
 ROUND(100.0*SUM(MARGEN_BRUTO_USD)/NULLIF(SUM(MONTO_NETO_USD),0),2) AS MARGEN_BRUTO_PCT
 FROM V_BI_LINEAS GROUP BY FECHA_MES,PERIOD_TX) a ORDER BY FECHA_MES;
