SET DEFINE OFF
ALTER SESSION SET CURRENT_SCHEMA = OMNI_DW;

PROMPT 01_RESUMEN_EJECUTIVO
SELECT COUNT(DISTINCT CODIGO_TRANSACCION) AS NUM_COMPRAS,
       COUNT(DISTINCT ID_CLIENTE_OLTP) AS CLIENTES,
       SUM(CANTIDAD) AS UNIDADES,
       SUM(MONTO_NETO_USD) AS VENTA_NETA_USD,
       SUM(TOTAL_LINEA_USD) AS VENTA_TOTAL_USD,
       SUM(COSTO_TOTAL_USD) AS COSTO_USD,
       SUM(MARGEN_BRUTO_USD) AS UTILIDAD_TOTAL_USD,
       ROUND(SUM(TOTAL_LINEA_USD)/NULLIF(COUNT(DISTINCT CODIGO_TRANSACCION),0),2) AS TICKET_PROMEDIO_USD,
       ROUND(100*SUM(MARGEN_BRUTO_USD)/NULLIF(SUM(MONTO_NETO_USD),0),2) AS MARGEN_BRUTO_PCT
  FROM V_BI_LINEAS;

PROMPT 02_EVOLUCION_MENSUAL_MOM
SELECT a.*,
       ROUND(VENTA_NETA_USD-LAG(VENTA_NETA_USD) OVER (ORDER BY FECHA_MES),2) AS VARIACION_USD,
       ROUND(100.0*(VENTA_NETA_USD-LAG(VENTA_NETA_USD) OVER (ORDER BY FECHA_MES))/NULLIF(LAG(VENTA_NETA_USD) OVER (ORDER BY FECHA_MES),0),2) AS VARIACION_MOM_PCT
  FROM (SELECT FECHA_MES, PERIOD_TX,
               COUNT(DISTINCT CODIGO_TRANSACCION) AS NUM_COMPRAS,
               COUNT(DISTINCT ID_CLIENTE_OLTP) AS CLIENTES,
               SUM(CANTIDAD) AS UNIDADES,
               ROUND(SUM(MONTO_NETO_USD),2) AS VENTA_NETA_USD,
               ROUND(SUM(TOTAL_LINEA_USD),2) AS VENTA_TOTAL_USD,
               ROUND(SUM(COSTO_TOTAL_USD),2) AS COSTO_USD,
               ROUND(SUM(MARGEN_BRUTO_USD),2) AS UTILIDAD_USD,
               ROUND(SUM(TOTAL_LINEA_USD)/NULLIF(COUNT(DISTINCT CODIGO_TRANSACCION),0),2) AS TICKET_PROMEDIO_USD,
               ROUND(100.0*SUM(MARGEN_BRUTO_USD)/NULLIF(SUM(MONTO_NETO_USD),0),2) AS MARGEN_BRUTO_PCT
          FROM V_BI_LINEAS GROUP BY FECHA_MES, PERIOD_TX) a
 ORDER BY FECHA_MES;

PROMPT 03_MES_POR_CANAL
SELECT FECHA_MES, CODIGO_CANAL, COUNT(DISTINCT CODIGO_TRANSACCION) AS NUM_COMPRAS,
       SUM(TOTAL_LINEA_USD) AS VENTA_TOTAL_USD,
       ROUND(SUM(TOTAL_LINEA_USD)/NULLIF(COUNT(DISTINCT CODIGO_TRANSACCION),0),2) AS TICKET_PROMEDIO_USD
  FROM V_BI_LINEAS GROUP BY FECHA_MES, CODIGO_CANAL ORDER BY FECHA_MES, CODIGO_CANAL;

PROMPT 04_CLIENTES_PERIODO
SELECT ID_CLIENTE_OLTP, CLIENTE, SEGMENTO, SUM(NUM_COMPRAS) AS NUM_COMPRAS,
       MIN(FECHA) AS PRIMERA_COMPRA_PERIODO, MAX(FECHA) AS ULTIMA_COMPRA_PERIODO,
       SUM(VENTA_TOTAL_USD) AS VENTA_TOTAL_USD,
       ROUND(SUM(VENTA_TOTAL_USD)/NULLIF(SUM(NUM_COMPRAS),0),2) AS TICKET_PROMEDIO_USD
  FROM MV_FRECUENCIA_CLIENTES
 WHERE FECHA >= DATE '2026-01-01' AND FECHA < DATE '2026-10-01'
 GROUP BY ID_CLIENTE_OLTP, CLIENTE, SEGMENTO;

PROMPT 05_FRECUENCIA_POR_SEGMENTO
SELECT SEGMENTO, COUNT(DISTINCT ID_CLIENTE_OLTP) AS CLIENTES,
       SUM(NUM_COMPRAS) AS NUM_COMPRAS,
       ROUND(SUM(NUM_COMPRAS)*1.0/NULLIF(COUNT(DISTINCT ID_CLIENTE_OLTP),0),2) AS COMPRAS_POR_CLIENTE,
       ROUND(SUM(VENTA_TOTAL_USD)/NULLIF(SUM(NUM_COMPRAS),0),2) AS TICKET_PROMEDIO_USD
  FROM MV_FRECUENCIA_CLIENTES GROUP BY SEGMENTO;

PROMPT 06_TOP_PRODUCTOS
SELECT a.*,
       RANK() OVER (ORDER BY UNIDADES DESC) AS RANKING_UNIDADES,
       RANK() OVER (ORDER BY VENTA_NETA_USD DESC) AS RANKING_VENTAS
  FROM (SELECT NOMBRE_PRODUCTO, SUM(UNIDADES) AS UNIDADES, SUM(VENTA_NETA_USD) AS VENTA_NETA_USD
          FROM MV_TOP_PRODUCTOS GROUP BY NOMBRE_PRODUCTO) a;

PROMPT 07_COBERTURA_PROMOCIONES
SELECT PROMOCION_ESPERADA,
       SUM(CASE WHEN NUM_PROMOCIONES_ELEGIBLES=1 THEN 1 ELSE 0 END) AS LINEAS_ELEGIBLES,
       SUM(CASE WHEN NUM_PROMOCIONES_ELEGIBLES=1 AND FUE_APLICADA='S' AND FUE_VALIDA='S' THEN 1 ELSE 0 END) AS LINEAS_APLICADAS_VALIDAS,
       SUM(CASE WHEN ESTADO_PROMOCION='ESPERADA_NO_APLICADA' THEN 1 ELSE 0 END) AS LINEAS_NO_APLICADAS,
       ROUND(100.0*SUM(CASE WHEN NUM_PROMOCIONES_ELEGIBLES=1 AND FUE_APLICADA='S' AND FUE_VALIDA='S' THEN 1 ELSE 0 END)
       /NULLIF(SUM(CASE WHEN NUM_PROMOCIONES_ELEGIBLES=1 THEN 1 ELSE 0 END),0),2) AS COBERTURA_PROMOCION_PCT
  FROM MV_PROMOCIONES_USADAS GROUP BY PROMOCION_ESPERADA;

PROMPT 08_UTILIDAD_POR_CATEGORIA
SELECT CATEGORIA, SUBCATEGORIA, SUM(VENTA_NETA_USD) AS VENTA_NETA_USD,
       SUM(COSTO_USD) AS COSTO_USD, SUM(UTILIDAD_TOTAL_USD) AS UTILIDAD_TOTAL_USD,
       ROUND(100*SUM(UTILIDAD_TOTAL_USD)/NULLIF(SUM(VENTA_NETA_USD),0),2) AS MARGEN_BRUTO_PCT
  FROM MV_UTILIDAD_POR_CATEGORIA GROUP BY CATEGORIA, SUBCATEGORIA;

PROMPT 09_TENDENCIA_DIARIA
SELECT FECHA, CODIGO_CANAL, COUNT(DISTINCT CODIGO_TRANSACCION) AS NUM_COMPRAS,
       SUM(TOTAL_LINEA_USD) AS VENTA_TOTAL_USD
  FROM V_BI_LINEAS GROUP BY FECHA, CODIGO_CANAL ORDER BY FECHA, CODIGO_CANAL;

PROMPT 10_TOTALES_ACUMULADOS
SELECT FECHA, VENTA_TOTAL_USD,
       LAG(VENTA_TOTAL_USD) OVER (ORDER BY FECHA) AS VENTA_DIA_ANTERIOR_CON_VENTAS,
       SUM(VENTA_TOTAL_USD) OVER (ORDER BY FECHA ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS VENTA_ACUMULADA_USD
  FROM (SELECT FECHA, SUM(TOTAL_LINEA_USD) AS VENTA_TOTAL_USD FROM V_BI_LINEAS GROUP BY FECHA) a
 ORDER BY FECHA;

PROMPT 11_INTERVALO_MEDIO_ENTRE_COMPRAS
SELECT ID_CLIENTE_OLTP, CLIENTE, COUNT(*) AS NUM_COMPRAS,
       ROUND((MAX(FECHA)-MIN(FECHA))/NULLIF(COUNT(*)-1,0),1) AS DIAS_ENTRE_COMPRAS
  FROM (SELECT ID_CLIENTE_OLTP, CLIENTE, CODIGO_TRANSACCION, MIN(FECHA) AS FECHA
          FROM V_BI_LINEAS WHERE FECHA >= DATE '2026-01-01' AND FECHA < DATE '2026-10-01'
         GROUP BY ID_CLIENTE_OLTP, CLIENTE, CODIGO_TRANSACCION)
 GROUP BY ID_CLIENTE_OLTP, CLIENTE;
