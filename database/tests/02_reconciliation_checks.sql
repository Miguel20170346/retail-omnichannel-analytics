DECLARE v_base NUMBER;v_mv NUMBER; BEGIN
 SELECT COUNT(*) INTO v_base FROM HECHOS_VENTAS;
 SELECT COUNT(*) INTO v_mv FROM V_BI_LINEAS;
 IF v_base<>v_mv THEN RAISE_APPLICATION_ERROR(-20055,'JOINs pierden o duplican lineas'); END IF;
 SELECT COUNT(*) INTO v_mv FROM MV_PROMOCIONES_USADAS;
 IF v_base<>v_mv THEN RAISE_APPLICATION_ERROR(-20056,'Promociones no conserva una fila por linea'); END IF;
 SELECT COUNT(DISTINCT CODIGO_TRANSACCION) INTO v_base FROM HECHOS_VENTAS;
 SELECT SUM(NUM_COMPRAS) INTO v_mv FROM MV_FRECUENCIA_CLIENTES;
 IF v_base<>NVL(v_mv,0) THEN RAISE_APPLICATION_ERROR(-20057,'Compras no concilian'); END IF;
 SELECT NVL(SUM(TOTAL_LINEA_USD),0) INTO v_base FROM HECHOS_VENTAS;
 FOR r IN (SELECT NVL(SUM(VENTA_TOTAL_USD),0) AS total FROM MV_VENTAS_MENSUALES
 UNION ALL SELECT NVL(SUM(VENTA_TOTAL_USD),0) FROM MV_TOP_PRODUCTOS
 UNION ALL SELECT NVL(SUM(VENTA_TOTAL_USD),0) FROM MV_FRECUENCIA_CLIENTES
 UNION ALL SELECT NVL(SUM(VENTA_TOTAL_USD),0) FROM MV_PROMOCIONES_USADAS) LOOP
 IF v_base<>r.total THEN RAISE_APPLICATION_ERROR(-20058,'Venta total no concilia'); END IF;
 END LOOP;
 SELECT NVL(SUM(MONTO_NETO_USD),0) INTO v_base FROM HECHOS_VENTAS;
 FOR r IN (SELECT NVL(SUM(VENTA_NETA_USD),0) AS total FROM MV_VENTAS_MENSUALES
 UNION ALL SELECT NVL(SUM(VENTA_NETA_USD),0) FROM MV_TOP_PRODUCTOS
 UNION ALL SELECT NVL(SUM(VENTA_NETA_USD),0) FROM MV_FRECUENCIA_CLIENTES
 UNION ALL SELECT NVL(SUM(VENTA_NETA_USD),0) FROM MV_UTILIDAD_POR_CATEGORIA
 UNION ALL SELECT NVL(SUM(VENTA_NETA_USD),0) FROM MV_PROMOCIONES_USADAS) LOOP
 IF v_base<>r.total THEN RAISE_APPLICATION_ERROR(-20059,'Venta neta no concilia'); END IF;
 END LOOP;
 SELECT NVL(SUM(MARGEN_BRUTO_USD),0) INTO v_base FROM HECHOS_VENTAS;
 FOR r IN (SELECT NVL(SUM(MARGEN_BRUTO_USD),0) AS total FROM MV_VENTAS_MENSUALES
 UNION ALL SELECT NVL(SUM(MARGEN_BRUTO_USD),0) FROM MV_TOP_PRODUCTOS
 UNION ALL SELECT NVL(SUM(MARGEN_BRUTO_USD),0) FROM MV_FRECUENCIA_CLIENTES
 UNION ALL SELECT NVL(SUM(UTILIDAD_TOTAL_USD),0) FROM MV_UTILIDAD_POR_CATEGORIA
 UNION ALL SELECT NVL(SUM(MARGEN_BRUTO_USD),0) FROM MV_PROMOCIONES_USADAS) LOOP
 IF v_base<>r.total THEN RAISE_APPLICATION_ERROR(-20060,'Utilidad no concilia'); END IF;
 END LOOP;
 SELECT NVL(SUM(COSTO_TOTAL_USD),0) INTO v_base FROM HECHOS_VENTAS;
 SELECT NVL(SUM(COSTO_USD),0) INTO v_mv FROM MV_UTILIDAD_POR_CATEGORIA;
 IF v_base<>v_mv THEN RAISE_APPLICATION_ERROR(-20061,'Costo no concilia'); END IF;
END;
