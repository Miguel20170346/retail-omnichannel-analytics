WITH h AS (
  SELECT SUM(MONTO_NETO_USD) AS NETO, SUM(TOTAL_LINEA_USD) AS TOTAL,
         SUM(COSTO_TOTAL_USD) AS COSTO, SUM(MARGEN_BRUTO_USD) AS UTILIDAD,
         COUNT(DISTINCT CODIGO_TRANSACCION) AS COMPRAS
    FROM HECHOS_VENTAS
)
SELECT 'MENSUALES' AS VISTA,
       (SELECT SUM(VENTA_NETA_USD) FROM MV_VENTAS_MENSUALES) - h.NETO AS DIF_NETA,
       (SELECT SUM(VENTA_TOTAL_USD) FROM MV_VENTAS_MENSUALES) - h.TOTAL AS DIF_TOTAL
  FROM h
UNION ALL
SELECT 'PRODUCTOS',
       (SELECT SUM(VENTA_NETA_USD) FROM MV_TOP_PRODUCTOS) - h.NETO,
       (SELECT SUM(VENTA_TOTAL_USD) FROM MV_TOP_PRODUCTOS) - h.TOTAL
  FROM h
UNION ALL
SELECT 'CLIENTES',
       (SELECT SUM(VENTA_NETA_USD) FROM MV_FRECUENCIA_CLIENTES) - h.NETO,
       (SELECT SUM(VENTA_TOTAL_USD) FROM MV_FRECUENCIA_CLIENTES) - h.TOTAL
  FROM h
UNION ALL
SELECT 'PROMOCIONES',
       (SELECT SUM(VENTA_NETA_USD) FROM MV_PROMOCIONES_USADAS) - h.NETO,
       (SELECT SUM(VENTA_TOTAL_USD) FROM MV_PROMOCIONES_USADAS) - h.TOTAL
  FROM h;

WITH h AS (
  SELECT SUM(COSTO_TOTAL_USD) AS COSTO, SUM(MARGEN_BRUTO_USD) AS UTILIDAD,
         COUNT(DISTINCT CODIGO_TRANSACCION) AS COMPRAS
    FROM HECHOS_VENTAS
)
SELECT (SELECT SUM(COSTO_USD) FROM MV_UTILIDAD_POR_CATEGORIA) - h.COSTO AS DIF_COSTO,
       (SELECT SUM(UTILIDAD_TOTAL_USD) FROM MV_UTILIDAD_POR_CATEGORIA) - h.UTILIDAD AS DIF_UTILIDAD,
       (SELECT SUM(NUM_COMPRAS) FROM MV_FRECUENCIA_CLIENTES) - h.COMPRAS AS DIF_COMPRAS
  FROM h;
SELECT ESTADO_PROMOCION,COUNT(*) AS LINEAS FROM MV_PROMOCIONES_USADAS GROUP BY ESTADO_PROMOCION;
