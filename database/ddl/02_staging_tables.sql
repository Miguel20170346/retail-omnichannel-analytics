-- Staging es una "zona de aterrizaje": copia los datos del OLTP SIN
-- restricciones (sin PK/FK/CHECK) para que los datos malos tambien
-- lleguen y la capa de calidad pueda detectarlos y registrarlos.
-- Se vacia al inicio de cada ejecucion del ETL; la trazabilidad
-- permanente queda en AUDITORIA_ETL_VENTAS y ERRORES_ETL_VENTAS.
-- =====================================================================
SET DEFINE OFF

-- Ventas a nivel de linea (grano = 1 producto dentro de 1 transaccion)
CREATE TABLE STG_VENTAS (
  ID_EJECUCION         NUMBER,
  ID_TRANSACCION       NUMBER,
  ID_DETALLE           NUMBER,
  FECHA_TRANSACCION    TIMESTAMP,
  CODIGO_CANAL         VARCHAR2(10),
  ID_CLIENTE           NUMBER,
  ID_EMPLEADO          NUMBER,
  NOMBRE_METODO_PAGO   VARCHAR2(100),
  NOMBRE_ESTADO        VARCHAR2(50),
  MONEDA_ORIGEN        VARCHAR2(10),
  TOTAL_CABECERA       NUMBER,
  ID_PRODUCTO          NUMBER,
  ID_PROMOCION         NUMBER,
  CANTIDAD             NUMBER,
  PRECIO_UNITARIO      NUMBER,
  DESCUENTO            NUMBER,
  IMPUESTO             NUMBER,
  -- Columnas calculadas durante la validacion / transformacion
  TASA_USD             NUMBER,
  CODIGO_TRANSACCION   VARCHAR2(40),
  HASH_REGISTRO        VARCHAR2(64),
  ESTADO_VALIDACION    VARCHAR2(12) DEFAULT 'PENDIENTE',
  FECHA_CARGA_STG      TIMESTAMP DEFAULT SYSTIMESTAMP
);
CREATE INDEX IX_STG_VENTAS_TRX ON STG_VENTAS (ID_TRANSACCION);
CREATE INDEX IX_STG_VENTAS_DET ON STG_VENTAS (ID_DETALLE);

-- Catalogos: fotografia completa en cada ejecucion
CREATE TABLE STG_CLIENTES (
  ID_CLIENTE NUMBER, NOMBRE VARCHAR2(100), EMAIL VARCHAR2(150), SEGMENTO VARCHAR2(50),
  ID_PAIS NUMBER, CODIGO_PAIS VARCHAR2(2), NOMBRE_PAIS VARCHAR2(100),
  ID_DEPARTAMENTO NUMBER, PAIS_DEPARTAMENTO NUMBER, NOMBRE_DEPARTAMENTO VARCHAR2(100),
  ID_ZONA NUMBER, PAIS_ZONA NUMBER, NOMBRE_ZONA VARCHAR2(100),
  FECHA_REGISTRO DATE, ACTIVO CHAR(1)
);

CREATE TABLE STG_PRODUCTOS (
  ID_PRODUCTO NUMBER, NOMBRE_PRODUCTO VARCHAR2(200),
  NOMBRE_CATEGORIA VARCHAR2(100), CATEGORIA_PADRE VARCHAR2(100),
  NOMBRE_MARCA VARCHAR2(100), NOMBRE_PROVEEDOR VARCHAR2(200),
  PRECIO_BASE NUMBER, COSTO_UNITARIO_USD NUMBER,
  FECHA_INICIO DATE, FECHA_FIN DATE          -- vigencia del precio
);

CREATE TABLE STG_EMPLEADOS (
  ID_EMPLEADO NUMBER, NOMBRE VARCHAR2(150), CARGO VARCHAR2(100),
  CODIGO_SUCURSAL VARCHAR2(15), NOMBRE_SUCURSAL VARCHAR2(150),
  NOMBRE_DEPARTAMENTO VARCHAR2(100), NOMBRE_PAIS VARCHAR2(100), ACTIVO CHAR(1)
);

CREATE TABLE STG_PROMOCIONES (
  ID_PROMOCION NUMBER, ID_PRODUCTO NUMBER, TIPO VARCHAR2(50), VALOR NUMBER,
  FECHA_INICIO DATE, FECHA_FIN DATE, DESCRIPCION VARCHAR2(500), ACTIVO CHAR(1)
);

