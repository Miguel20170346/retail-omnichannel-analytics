SET DEFINE OFF

-- 1. TRX_PAISES ---------------------------------------------------------
CREATE TABLE TRX_PAISES (
  ID_PAIS          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  CODIGO_PAIS      VARCHAR2(2)   NOT NULL,
  NOMBRE_PAIS      VARCHAR2(100) NOT NULL,
  MONEDA_OFICIAL   VARCHAR2(3)   NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  CONSTRAINT PK_TRX_PAISES      PRIMARY KEY (ID_PAIS),
  CONSTRAINT UQ_TRX_PAISES_COD  UNIQUE (CODIGO_PAIS),
  CONSTRAINT CK_TRX_PAISES_ACT  CHECK (ACTIVO IN ('S','N'))
);

-- 2. TRX_CANALES --------------------------------------------------------
CREATE TABLE TRX_CANALES (
  ID_CANAL         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  CODIGO_CANAL     VARCHAR2(10)  NOT NULL,
  NOMBRE_CANAL     VARCHAR2(50)  NOT NULL,
  DESCRIPCION      VARCHAR2(200),
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_CANALES      PRIMARY KEY (ID_CANAL),
  CONSTRAINT UQ_TRX_CANALES_COD  UNIQUE (CODIGO_CANAL),
  CONSTRAINT CK_TRX_CANALES_ACT  CHECK (ACTIVO IN ('S','N'))
);

-- 3. TRX_ESTADOS_VENTA --------------------------------------------------
CREATE TABLE TRX_ESTADOS_VENTA (
  ID_ESTADO_VENTA  NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE_ESTADO    VARCHAR2(50)  NOT NULL,
  DESCRIPCION      VARCHAR2(200),
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_ESTADOS_VENTA     PRIMARY KEY (ID_ESTADO_VENTA),
  CONSTRAINT UQ_TRX_ESTADOS_VENTA_NOM UNIQUE (NOMBRE_ESTADO),
  CONSTRAINT CK_TRX_ESTADOS_VENTA_ACT CHECK (ACTIVO IN ('S','N'))
);

-- 4. TRX_METODOS_PAGO ---------------------------------------------------
CREATE TABLE TRX_METODOS_PAGO (
  ID_METODO_PAGO   NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE_METODO    VARCHAR2(100) NOT NULL,
  DESCRIPCION      VARCHAR2(300),
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_METODOS_PAGO     PRIMARY KEY (ID_METODO_PAGO),
  CONSTRAINT UQ_TRX_METODOS_PAGO_NOM UNIQUE (NOMBRE_METODO),
  CONSTRAINT CK_TRX_METODOS_PAGO_ACT CHECK (ACTIVO IN ('S','N'))
);

-- 5. TRX_CATEGORIAS_PRODUCTO (jerarquia padre-hijo) ---------------------
CREATE TABLE TRX_CATEGORIAS_PRODUCTO (
  ID_CATEGORIA        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_CATEGORIA_PADRE  NUMBER,
  NOMBRE_CATEGORIA    VARCHAR2(100) NOT NULL,
  DESCRIPCION         VARCHAR2(500),
  ACTIVO              CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_CATEGORIAS      PRIMARY KEY (ID_CATEGORIA),
  CONSTRAINT UQ_TRX_CATEGORIAS_NOM  UNIQUE (NOMBRE_CATEGORIA),
  CONSTRAINT FK_TRX_CATEGORIAS_PAD  FOREIGN KEY (ID_CATEGORIA_PADRE)
                                    REFERENCES TRX_CATEGORIAS_PRODUCTO (ID_CATEGORIA),
  CONSTRAINT CK_TRX_CATEGORIAS_ACT  CHECK (ACTIVO IN ('S','N'))
);

-- 6. TRX_MONEDAS (historico diario de tasas) ----------------------------
--    TASA_USD = cuantos USD vale 1 unidad de MONEDA_ORIGEN.
CREATE TABLE TRX_MONEDAS (
  ID_MONEDA           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  FECHA               DATE          NOT NULL,
  MONEDA_ORIGEN       VARCHAR2(3)   NOT NULL,
  TASA_USD            NUMBER(18,6)  NOT NULL,
  FUENTE_TIPO_CAMBIO  VARCHAR2(200),
  ACTIVO              CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_MONEDAS         PRIMARY KEY (ID_MONEDA),
  CONSTRAINT UQ_TRX_MONEDAS_FEC_MON UNIQUE (FECHA, MONEDA_ORIGEN),
  CONSTRAINT CK_TRX_MONEDAS_MON     CHECK (MONEDA_ORIGEN IN ('USD','EUR','GTQ')),
  CONSTRAINT CK_TRX_MONEDAS_TASA    CHECK (TASA_USD > 0),
  CONSTRAINT CK_TRX_MONEDAS_FECHA   CHECK (FECHA = TRUNC(FECHA)),
  CONSTRAINT CK_TRX_MONEDAS_ACT     CHECK (ACTIVO IN ('S','N'))
);

-- 7. TRX_DEPARTAMENTOS --------------------------------------------------
CREATE TABLE TRX_DEPARTAMENTOS (
  ID_DEPARTAMENTO      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_PAIS              NUMBER        NOT NULL,
  CODIGO_DEPARTAMENTO  VARCHAR2(10)  NOT NULL,
  NOMBRE_DEPARTAMENTO  VARCHAR2(100) NOT NULL,
  FECHA_CREACION       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  ACTIVO               CHAR(1)       DEFAULT 'S' NOT NULL,
  CONSTRAINT PK_TRX_DEPARTAMENTOS      PRIMARY KEY (ID_DEPARTAMENTO),
  CONSTRAINT FK_TRX_DEPARTAMENTOS_PAIS FOREIGN KEY (ID_PAIS) REFERENCES TRX_PAISES (ID_PAIS),
  CONSTRAINT UQ_TRX_DEPARTAMENTOS_COD  UNIQUE (ID_PAIS, CODIGO_DEPARTAMENTO),
  CONSTRAINT CK_TRX_DEPARTAMENTOS_ACT  CHECK (ACTIVO IN ('S','N'))
);

-- 8. TRX_ZONAS ----------------------------------------------------------
CREATE TABLE TRX_ZONAS (
  ID_ZONA          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_PAIS          NUMBER        NOT NULL,
  CODIGO_ZONA      VARCHAR2(20)  NOT NULL,
  NOMBRE_ZONA      VARCHAR2(100) NOT NULL,
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_ZONAS      PRIMARY KEY (ID_ZONA),
  CONSTRAINT FK_TRX_ZONAS_PAIS FOREIGN KEY (ID_PAIS) REFERENCES TRX_PAISES (ID_PAIS),
  CONSTRAINT UQ_TRX_ZONAS_COD  UNIQUE (ID_PAIS, CODIGO_ZONA),
  CONSTRAINT CK_TRX_ZONAS_ACT  CHECK (ACTIVO IN ('S','N'))
);

-- 9. TRX_MARCAS ---------------------------------------------------------
CREATE TABLE TRX_MARCAS (
  ID_MARCA         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE_MARCA     VARCHAR2(100) NOT NULL,
  ID_PAIS_ORIGEN   NUMBER,
  SITIO_WEB        VARCHAR2(250),
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_MARCAS      PRIMARY KEY (ID_MARCA),
  CONSTRAINT UQ_TRX_MARCAS_NOM  UNIQUE (NOMBRE_MARCA),
  CONSTRAINT FK_TRX_MARCAS_PAIS FOREIGN KEY (ID_PAIS_ORIGEN) REFERENCES TRX_PAISES (ID_PAIS),
  CONSTRAINT CK_TRX_MARCAS_ACT  CHECK (ACTIVO IN ('S','N'))
);

-- 10. TRX_PROVEEDORES ---------------------------------------------------
CREATE TABLE TRX_PROVEEDORES (
  ID_PROVEEDOR        NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE_PROVEEDOR    VARCHAR2(200) NOT NULL,
  ID_PAIS             NUMBER,
  NOMBRE_CONTACTO     VARCHAR2(150),
  TELEFONO            VARCHAR2(30),
  CORREO_ELECTRONICO  VARCHAR2(150),
  DIRECCION           VARCHAR2(500),
  ACTIVO              CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_PROVEEDORES      PRIMARY KEY (ID_PROVEEDOR),
  CONSTRAINT UQ_TRX_PROVEEDORES_NOM  UNIQUE (NOMBRE_PROVEEDOR),
  CONSTRAINT FK_TRX_PROVEEDORES_PAIS FOREIGN KEY (ID_PAIS) REFERENCES TRX_PAISES (ID_PAIS),
  CONSTRAINT CK_TRX_PROVEEDORES_ACT  CHECK (ACTIVO IN ('S','N'))
);

-- 11. TRX_SUCURSALES ----------------------------------------------------
CREATE TABLE TRX_SUCURSALES (
  ID_SUCURSAL      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_DEPARTAMENTO  NUMBER        NOT NULL,
  CODIGO_SUCURSAL  VARCHAR2(15)  NOT NULL,
  NOMBRE_SUCURSAL  VARCHAR2(150) NOT NULL,
  DIRECCION        VARCHAR2(500),
  TELEFONO         VARCHAR2(30),
  EMAIL            VARCHAR2(150),
  FECHA_APERTURA   DATE,
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_SUCURSALES     PRIMARY KEY (ID_SUCURSAL),
  CONSTRAINT UQ_TRX_SUCURSALES_COD UNIQUE (CODIGO_SUCURSAL),
  CONSTRAINT FK_TRX_SUCURSALES_DEP FOREIGN KEY (ID_DEPARTAMENTO) REFERENCES TRX_DEPARTAMENTOS (ID_DEPARTAMENTO),
  CONSTRAINT CK_TRX_SUCURSALES_ACT CHECK (ACTIVO IN ('S','N'))
);

-- 12. TRX_CLIENTES ------------------------------------------------------
CREATE TABLE TRX_CLIENTES (
  ID_CLIENTE       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE           VARCHAR2(100) NOT NULL,
  EMAIL            VARCHAR2(150),
  TELEFONO         VARCHAR2(30),
  ID_PAIS          NUMBER        NOT NULL,
  ID_DEPARTAMENTO  NUMBER        NOT NULL,
  ID_ZONA          NUMBER        NOT NULL,
  DIRECCION        VARCHAR2(500),
  SEGMENTO         VARCHAR2(50)  NOT NULL,
  FECHA_REGISTRO   DATE          DEFAULT SYSDATE,
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_CLIENTES       PRIMARY KEY (ID_CLIENTE),
  CONSTRAINT UQ_TRX_CLIENTES_EMAIL UNIQUE (EMAIL),
  CONSTRAINT FK_TRX_CLIENTES_PAIS  FOREIGN KEY (ID_PAIS)         REFERENCES TRX_PAISES (ID_PAIS),
  CONSTRAINT FK_TRX_CLIENTES_DEP   FOREIGN KEY (ID_DEPARTAMENTO) REFERENCES TRX_DEPARTAMENTOS (ID_DEPARTAMENTO),
  CONSTRAINT FK_TRX_CLIENTES_ZONA  FOREIGN KEY (ID_ZONA)         REFERENCES TRX_ZONAS (ID_ZONA),
  CONSTRAINT CK_TRX_CLIENTES_ACT   CHECK (ACTIVO IN ('S','N'))
);

-- 13. TRX_PRODUCTOS -----------------------------------------------------
--     PRECIO_BASE y COSTO_UNITARIO_USD se expresan en USD.
CREATE TABLE TRX_PRODUCTOS (
  ID_PRODUCTO          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE_PRODUCTO      VARCHAR2(200) NOT NULL,
  ID_CATEGORIA         NUMBER        NOT NULL,
  ID_MARCA             NUMBER        NOT NULL,
  ID_PROVEEDOR         NUMBER        NOT NULL,
  PRECIO_BASE          NUMBER(12,2)  NOT NULL,
  COSTO_UNITARIO_USD   NUMBER(12,2),            -- decision punto 3 (margen)
  FECHA_INICIO_PRECIO  DATE,                    -- decision punto 2 (vigencia)
  FECHA_FIN_PRECIO     DATE,                    -- NULL = vigente sin fecha fin
  FECHA_CREACION       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_PRODUCTOS        PRIMARY KEY (ID_PRODUCTO),
  CONSTRAINT FK_TRX_PRODUCTOS_CAT    FOREIGN KEY (ID_CATEGORIA) REFERENCES TRX_CATEGORIAS_PRODUCTO (ID_CATEGORIA),
  CONSTRAINT FK_TRX_PRODUCTOS_MARCA  FOREIGN KEY (ID_MARCA)     REFERENCES TRX_MARCAS (ID_MARCA),
  CONSTRAINT FK_TRX_PRODUCTOS_PROV   FOREIGN KEY (ID_PROVEEDOR) REFERENCES TRX_PROVEEDORES (ID_PROVEEDOR),
  CONSTRAINT CK_TRX_PRODUCTOS_PRECIO CHECK (PRECIO_BASE > 0),
  CONSTRAINT CK_TRX_PRODUCTOS_COSTO  CHECK (COSTO_UNITARIO_USD IS NULL OR COSTO_UNITARIO_USD >= 0),
  CONSTRAINT CK_TRX_PRODUCTOS_VIG    CHECK (FECHA_FIN_PRECIO IS NULL OR FECHA_INICIO_PRECIO IS NULL
                                            OR FECHA_FIN_PRECIO >= FECHA_INICIO_PRECIO)
);

-- 14. TRX_EMPLEADOS -----------------------------------------------------
CREATE TABLE TRX_EMPLEADOS (
  ID_EMPLEADO         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  NOMBRE              VARCHAR2(150) NOT NULL,
  EMAIL               VARCHAR2(150),
  TELEFONO            VARCHAR2(30),
  CARGO               VARCHAR2(100) NOT NULL,
  ID_SUCURSAL         NUMBER        NOT NULL,
  FECHA_CONTRATACION  DATE,
  ACTIVO              CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_EMPLEADOS       PRIMARY KEY (ID_EMPLEADO),
  CONSTRAINT UQ_TRX_EMPLEADOS_EMAIL UNIQUE (EMAIL),
  CONSTRAINT FK_TRX_EMPLEADOS_SUC   FOREIGN KEY (ID_SUCURSAL) REFERENCES TRX_SUCURSALES (ID_SUCURSAL),
  CONSTRAINT CK_TRX_EMPLEADOS_ACT   CHECK (ACTIVO IN ('S','N'))
);

-- 15. TRX_PROMOCIONES ---------------------------------------------------
--     TIPO: 'MONTO' (VALOR en USD por unidad) o 'PORCENTAJE' (VALOR = %).
CREATE TABLE TRX_PROMOCIONES (
  ID_PROMOCION     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_PRODUCTO      NUMBER        NOT NULL,
  TIPO             VARCHAR2(50)  NOT NULL,
  VALOR            NUMBER(10,2)  NOT NULL,
  FECHA_INICIO     DATE          NOT NULL,
  FECHA_FIN        DATE          NOT NULL,
  DESCRIPCION      VARCHAR2(500),
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_PROMOCIONES       PRIMARY KEY (ID_PROMOCION),
  CONSTRAINT FK_TRX_PROMOCIONES_PROD  FOREIGN KEY (ID_PRODUCTO) REFERENCES TRX_PRODUCTOS (ID_PRODUCTO),
  CONSTRAINT CK_TRX_PROMOCIONES_FEC   CHECK (FECHA_FIN >= FECHA_INICIO),
  CONSTRAINT CK_TRX_PROMOCIONES_VAL   CHECK (VALOR >= 0),
  CONSTRAINT CK_TRX_PROMOCIONES_ACT   CHECK (ACTIVO IN ('S','N'))
);

-- 16. TRX_VENTAS (cabecera) ---------------------------------------------
CREATE TABLE TRX_VENTAS (
  ID_TRANSACCION     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  FECHA_TRANSACCION  TIMESTAMP     NOT NULL,
  ID_CANAL           NUMBER        NOT NULL,
  ID_CLIENTE         NUMBER        NOT NULL,
  ID_EMPLEADO        NUMBER        NOT NULL,   -- WEB/MOB usan operador virtual (punto 5)
  ID_METODO_PAGO     NUMBER        NOT NULL,
  ID_ESTADO_VENTA    NUMBER        NOT NULL,
  MONEDA_ORIGEN      VARCHAR2(3)   NOT NULL,
  TOTAL              NUMBER(18,2)  NOT NULL,
  ACTIVO             CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_VENTAS         PRIMARY KEY (ID_TRANSACCION),
  CONSTRAINT FK_TRX_VENTAS_CANAL   FOREIGN KEY (ID_CANAL)        REFERENCES TRX_CANALES (ID_CANAL),
  CONSTRAINT FK_TRX_VENTAS_CLIENTE FOREIGN KEY (ID_CLIENTE)      REFERENCES TRX_CLIENTES (ID_CLIENTE),
  CONSTRAINT FK_TRX_VENTAS_EMP     FOREIGN KEY (ID_EMPLEADO)     REFERENCES TRX_EMPLEADOS (ID_EMPLEADO),
  CONSTRAINT FK_TRX_VENTAS_METODO  FOREIGN KEY (ID_METODO_PAGO)  REFERENCES TRX_METODOS_PAGO (ID_METODO_PAGO),
  CONSTRAINT FK_TRX_VENTAS_ESTADO  FOREIGN KEY (ID_ESTADO_VENTA) REFERENCES TRX_ESTADOS_VENTA (ID_ESTADO_VENTA),
  CONSTRAINT CK_TRX_VENTAS_MONEDA  CHECK (MONEDA_ORIGEN IN ('USD','EUR','GTQ')),
  CONSTRAINT CK_TRX_VENTAS_TOTAL   CHECK (TOTAL >= 0),
  CONSTRAINT CK_TRX_VENTAS_ACT     CHECK (ACTIVO IN ('S','N'))
);

CREATE INDEX IX_TRX_VENTAS_FECHA   ON TRX_VENTAS (FECHA_TRANSACCION);
CREATE INDEX IX_TRX_VENTAS_CANAL   ON TRX_VENTAS (ID_CANAL);
CREATE INDEX IX_TRX_VENTAS_CLIENTE ON TRX_VENTAS (ID_CLIENTE);
CREATE INDEX IX_TRX_VENTAS_EMP     ON TRX_VENTAS (ID_EMPLEADO);

-- 17. TRX_DETALLE (una fila = un producto vendido en la transaccion) ----
CREATE TABLE TRX_DETALLE (
  ID_DETALLE       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ID_TRANSACCION   NUMBER        NOT NULL,
  ID_PRODUCTO      NUMBER        NOT NULL,
  ID_PROMOCION     NUMBER,
  CANTIDAD         NUMBER(10)    NOT NULL,
  PRECIO_UNITARIO  NUMBER(18,2)  NOT NULL,
  DESCUENTO        NUMBER(18,2)  DEFAULT 0 NOT NULL,
  IMPUESTO         NUMBER(18,2)  DEFAULT 0 NOT NULL,
  ACTIVO           CHAR(1)       DEFAULT 'S' NOT NULL,
  FECHA_CREACION   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_TRX_DETALLE        PRIMARY KEY (ID_DETALLE),
  CONSTRAINT FK_TRX_DETALLE_VENTA  FOREIGN KEY (ID_TRANSACCION) REFERENCES TRX_VENTAS (ID_TRANSACCION),
  CONSTRAINT FK_TRX_DETALLE_PROD   FOREIGN KEY (ID_PRODUCTO)    REFERENCES TRX_PRODUCTOS (ID_PRODUCTO),
  CONSTRAINT FK_TRX_DETALLE_PROMO  FOREIGN KEY (ID_PROMOCION)   REFERENCES TRX_PROMOCIONES (ID_PROMOCION),
  CONSTRAINT CK_TRX_DETALLE_CANT   CHECK (CANTIDAD > 0),
  CONSTRAINT CK_TRX_DETALLE_PRECIO CHECK (PRECIO_UNITARIO >= 0),
  CONSTRAINT CK_TRX_DETALLE_DESC   CHECK (DESCUENTO >= 0),
  CONSTRAINT CK_TRX_DETALLE_IMP    CHECK (IMPUESTO >= 0),
  CONSTRAINT CK_TRX_DETALLE_ACT    CHECK (ACTIVO IN ('S','N'))
);

CREATE INDEX IX_TRX_DETALLE_VENTA ON TRX_DETALLE (ID_TRANSACCION);
CREATE INDEX IX_TRX_DETALLE_PROD  ON TRX_DETALLE (ID_PRODUCTO);
CREATE INDEX IX_TRX_DETALLE_PROMO ON TRX_DETALLE (ID_PROMOCION);

