-- Decisiones consideradas para el modelo:
--   * TRX_PRODUCTOS: + COSTO_UNITARIO_USD, FECHA_INICIO_PRECIO,
--     FECHA_FIN_PRECIO  (puntos 2 y 3: vigencia de precio y margen).
--   * TRX_MONEDAS: UNIQUE (FECHA, MONEDA_ORIGEN) y FECHA sin hora,
--     para que el JOIN por fecha devuelva siempre una sola tasa.
--   * Indices sobre las FK de ventas y detalle.
