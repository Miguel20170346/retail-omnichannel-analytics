CREATE OR REPLACE VIEW V_BI_LINEAS AS
SELECT TRUNC(CAST(h.FECHA_HORA_TRANSACCION AS DATE)) AS FECHA,
 TRUNC(CAST(h.FECHA_HORA_TRANSACCION AS DATE),'MM') AS FECHA_MES,
 f.ANIO,f.MES,TO_CHAR(f.FECHA,'YYYYMM') AS PERIOD_TX,
 ca.CODIGO_CANAL,h.CODIGO_TRANSACCION,cl.ID_CLIENTE_OLTP,cl.NOMBRE AS CLIENTE,
 cl.SEGMENTO,cl.PAIS AS PAIS_CLIENTE,cl.DEPARTAMENTO,cl.ZONA,
 p.NOMBRE_PRODUCTO,NVL(p.CATEGORIA_PADRE,p.CATEGORIA) AS CATEGORIA,
 p.CATEGORIA AS SUBCATEGORIA,p.MARCA,pr.DESCRIPCION AS PROMOCION_APLICADA,
 h.MONEDA_ORIGEN,h.TASA_USD,h.CANTIDAD,h.PRECIO_UNITARIO_ORIGEN,
 h.MONTO_BRUTO_USD,h.DESCUENTO_USD,h.MONTO_NETO_USD,h.IMPUESTO_USD,
 h.TOTAL_LINEA_USD,h.COSTO_TOTAL_USD,h.MARGEN_BRUTO_USD
FROM HECHOS_VENTAS h
JOIN DIM_FECHA f ON f.SK_FECHA=h.SK_FECHA
JOIN DIM_CANAL ca ON ca.SK_CANAL=h.SK_CANAL
JOIN DIM_CLIENTE cl ON cl.SK_CLIENTE=h.SK_CLIENTE
JOIN DIM_PRODUCTO p ON p.SK_PRODUCTO=h.SK_PRODUCTO
JOIN DIM_PROMOCION pr ON pr.SK_PROMOCION=h.SK_PROMOCION;
CREATE OR REPLACE VIEW V_BI_PROMOCIONES AS
WITH elegibles AS (
 SELECT h.ID_HECHO,COUNT(pr.ID_PROMOCION) AS NUM_PROMOCIONES_ELEGIBLES,
 MAX(pr.DESCRIPCION) AS DESCRIPCION,MAX(pr.TIPO) AS TIPO,MAX(pr.VALOR) AS VALOR
 FROM HECHOS_VENTAS h JOIN DIM_PRODUCTO p ON p.SK_PRODUCTO=h.SK_PRODUCTO
 LEFT JOIN TRX_PROMOCIONES pr ON pr.ID_PRODUCTO=p.ID_PRODUCTO_OLTP AND pr.ACTIVO='S'
 AND TRUNC(CAST(h.FECHA_HORA_TRANSACCION AS DATE)) BETWEEN pr.FECHA_INICIO AND pr.FECHA_FIN
 GROUP BY h.ID_HECHO
), calculos AS (
 SELECT h.*,f.ANIO,f.MES,ca.CODIGO_CANAL,p.NOMBRE_PRODUCTO,
 NVL(p.CATEGORIA_PADRE,p.CATEGORIA) AS CATEGORIA,p.CATEGORIA AS SUBCATEGORIA,
 e.NUM_PROMOCIONES_ELEGIBLES,
 CASE WHEN e.NUM_PROMOCIONES_ELEGIBLES=1 THEN e.DESCRIPCION END AS PROMOCION_ESPERADA,
 dp.DESCRIPCION AS PROMOCION_APLICADA,
 CASE WHEN e.NUM_PROMOCIONES_ELEGIBLES=0 THEN 0 WHEN e.NUM_PROMOCIONES_ELEGIBLES=1 THEN
 ROUND(ROUND(CASE e.TIPO WHEN 'PORCENTAJE' THEN h.CANTIDAD*h.PRECIO_UNITARIO_ORIGEN*e.VALOR/100
 WHEN 'MONTO' THEN h.CANTIDAD*e.VALOR/h.TASA_USD END,2)*h.TASA_USD,2) END AS DESCUENTO_ESPERADO_USD,
 CASE WHEN h.SK_PROMOCION=0 THEN 'N' ELSE 'S' END AS FUE_APLICADA,
 CASE WHEN h.SK_PROMOCION=0 THEN NULL
 WHEN pr.ID_PRODUCTO=p.ID_PRODUCTO_OLTP AND pr.ACTIVO='S'
 AND TRUNC(CAST(h.FECHA_HORA_TRANSACCION AS DATE)) BETWEEN pr.FECHA_INICIO AND pr.FECHA_FIN
 AND ABS(h.DESCUENTO_USD-ROUND(ROUND(CASE pr.TIPO
 WHEN 'PORCENTAJE' THEN h.CANTIDAD*h.PRECIO_UNITARIO_ORIGEN*pr.VALOR/100
 WHEN 'MONTO' THEN h.CANTIDAD*pr.VALOR/h.TASA_USD END,2)*h.TASA_USD,2))<=0.02
 THEN 'S' ELSE 'N' END AS FUE_VALIDA
 FROM HECHOS_VENTAS h JOIN DIM_FECHA f ON f.SK_FECHA=h.SK_FECHA
 JOIN DIM_CANAL ca ON ca.SK_CANAL=h.SK_CANAL
 JOIN DIM_PRODUCTO p ON p.SK_PRODUCTO=h.SK_PRODUCTO
 JOIN DIM_PROMOCION dp ON dp.SK_PROMOCION=h.SK_PROMOCION
 JOIN elegibles e ON e.ID_HECHO=h.ID_HECHO
 LEFT JOIN TRX_PROMOCIONES pr ON pr.ID_PROMOCION=dp.ID_PROMOCION_OLTP
)
SELECT TRUNC(CAST(FECHA_HORA_TRANSACCION AS DATE)) AS FECHA,
 TRUNC(CAST(FECHA_HORA_TRANSACCION AS DATE),'MM') AS FECHA_MES,
 TO_CHAR(FECHA_HORA_TRANSACCION,'YYYYMM') AS PERIOD_TX,
 CODIGO_TRANSACCION,CODIGO_CANAL,NOMBRE_PRODUCTO,CATEGORIA,SUBCATEGORIA,CANTIDAD,
 PROMOCION_ESPERADA,NUM_PROMOCIONES_ELEGIBLES,PROMOCION_APLICADA,FUE_APLICADA,FUE_VALIDA,
 DESCUENTO_ESPERADO_USD,DESCUENTO_USD AS DESCUENTO_OTORGADO_USD,
 MONTO_NETO_USD AS VENTA_NETA_USD,TOTAL_LINEA_USD AS VENTA_TOTAL_USD,MARGEN_BRUTO_USD,
 CASE WHEN NUM_PROMOCIONES_ELEGIBLES>1 THEN 'PROMOCIONES_SUPERPUESTAS'
 WHEN FUE_APLICADA='S' AND FUE_VALIDA='N' THEN 'APLICADA_INVALIDA'
 WHEN FUE_APLICADA='S' THEN 'APLICADA_VALIDA'
 WHEN NUM_PROMOCIONES_ELEGIBLES=1 THEN 'ESPERADA_NO_APLICADA'
 WHEN DESCUENTO_USD<>0 THEN 'DESCUENTO_SIN_PROMOCION'
 ELSE 'SIN_PROMOCION_ESPERADA' END AS ESTADO_PROMOCION
FROM calculos;

CREATE MATERIALIZED VIEW MV_VENTAS_MENSUALES
BUILD IMMEDIATE REFRESH COMPLETE ON DEMAND AS
SELECT FECHA_MES, ANIO, MES, PERIOD_TX, CODIGO_CANAL, CATEGORIA, SUBCATEGORIA,
 COUNT(DISTINCT CODIGO_TRANSACCION) AS NUM_TRANSACCIONES_CATEGORIA,
 SUM(CANTIDAD) AS UNIDADES, SUM(MONTO_BRUTO_USD) AS VENTA_BRUTA_USD,
 SUM(DESCUENTO_USD) AS DESCUENTO_USD, SUM(MONTO_NETO_USD) AS VENTA_NETA_USD,
 SUM(IMPUESTO_USD) AS IMPUESTO_USD, SUM(TOTAL_LINEA_USD) AS VENTA_TOTAL_USD,
 SUM(MARGEN_BRUTO_USD) AS MARGEN_BRUTO_USD,
 ROUND(SUM(TOTAL_LINEA_USD)/NULLIF(COUNT(DISTINCT CODIGO_TRANSACCION),0),2) AS TICKET_CATEGORIA_USD
 FROM V_BI_LINEAS GROUP BY FECHA_MES,ANIO,MES,PERIOD_TX,CODIGO_CANAL,CATEGORIA,SUBCATEGORIA;

CREATE MATERIALIZED VIEW MV_TOP_PRODUCTOS
BUILD IMMEDIATE REFRESH COMPLETE ON DEMAND AS
SELECT a.*,
 RANK() OVER (PARTITION BY FECHA_MES,CODIGO_CANAL ORDER BY UNIDADES DESC) AS RANKING_UNIDADES,
 RANK() OVER (PARTITION BY FECHA_MES,CODIGO_CANAL ORDER BY VENTA_NETA_USD DESC) AS RANKING_VENTAS
 FROM (SELECT FECHA_MES,PERIOD_TX,CODIGO_CANAL,NOMBRE_PRODUCTO,CATEGORIA,SUBCATEGORIA,MARCA,
 COUNT(DISTINCT CODIGO_TRANSACCION) AS NUM_TRANSACCIONES_PRODUCTO,
 SUM(CANTIDAD) AS UNIDADES,SUM(MONTO_NETO_USD) AS VENTA_NETA_USD,
 SUM(TOTAL_LINEA_USD) AS VENTA_TOTAL_USD,SUM(MARGEN_BRUTO_USD) AS MARGEN_BRUTO_USD
 FROM V_BI_LINEAS GROUP BY FECHA_MES,PERIOD_TX,CODIGO_CANAL,NOMBRE_PRODUCTO,CATEGORIA,SUBCATEGORIA,MARCA) a;

CREATE MATERIALIZED VIEW MV_FRECUENCIA_CLIENTES
BUILD IMMEDIATE REFRESH COMPLETE ON DEMAND AS
SELECT FECHA,FECHA_MES,PERIOD_TX,CODIGO_CANAL,ID_CLIENTE_OLTP,CLIENTE,SEGMENTO,
 PAIS_CLIENTE,DEPARTAMENTO,ZONA,COUNT(DISTINCT CODIGO_TRANSACCION) AS NUM_COMPRAS,
 SUM(TOTAL_LINEA_USD) AS VENTA_TOTAL_USD,SUM(MONTO_NETO_USD) AS VENTA_NETA_USD,
 SUM(MARGEN_BRUTO_USD) AS MARGEN_BRUTO_USD,
 ROUND(SUM(TOTAL_LINEA_USD)/NULLIF(COUNT(DISTINCT CODIGO_TRANSACCION),0),2) AS TICKET_PROMEDIO_USD
 FROM V_BI_LINEAS GROUP BY FECHA,FECHA_MES,PERIOD_TX,CODIGO_CANAL,ID_CLIENTE_OLTP,CLIENTE,SEGMENTO,PAIS_CLIENTE,DEPARTAMENTO,ZONA;

CREATE MATERIALIZED VIEW MV_UTILIDAD_POR_CATEGORIA
BUILD IMMEDIATE REFRESH COMPLETE ON DEMAND AS
SELECT FECHA_MES,PERIOD_TX,CODIGO_CANAL,CATEGORIA,SUBCATEGORIA,
 SUM(CANTIDAD) AS UNIDADES,SUM(MONTO_NETO_USD) AS VENTA_NETA_USD,
 SUM(COSTO_TOTAL_USD) AS COSTO_USD,SUM(MARGEN_BRUTO_USD) AS UTILIDAD_TOTAL_USD,
 ROUND(100*SUM(MARGEN_BRUTO_USD)/NULLIF(SUM(MONTO_NETO_USD),0),2) AS MARGEN_BRUTO_PCT
 FROM V_BI_LINEAS GROUP BY FECHA_MES,PERIOD_TX,CODIGO_CANAL,CATEGORIA,SUBCATEGORIA;

CREATE MATERIALIZED VIEW MV_PROMOCIONES_USADAS
BUILD IMMEDIATE REFRESH COMPLETE ON DEMAND AS
SELECT FECHA,FECHA_MES,PERIOD_TX,CODIGO_TRANSACCION,CODIGO_CANAL,NOMBRE_PRODUCTO,CATEGORIA,SUBCATEGORIA,
 CANTIDAD,PROMOCION_ESPERADA,NUM_PROMOCIONES_ELEGIBLES,PROMOCION_APLICADA,FUE_APLICADA,FUE_VALIDA,
 DESCUENTO_ESPERADO_USD,DESCUENTO_OTORGADO_USD,VENTA_NETA_USD,VENTA_TOTAL_USD,MARGEN_BRUTO_USD,ESTADO_PROMOCION
 FROM V_BI_PROMOCIONES;

CREATE OR REPLACE PROCEDURE PR_REFRESCAR_MVS_KEYLA AS
 v_n NUMBER;
 v_esquema VARCHAR2(128) := SYS_CONTEXT('USERENV','CURRENT_USER');
BEGIN
 SELECT COUNT(*) INTO v_n FROM (SELECT NOMBRE_PRODUCTO FROM DIM_PRODUCTO GROUP BY NOMBRE_PRODUCTO HAVING COUNT(*)>1);
 IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20051,'Nombres de producto duplicados: exportar claves y actualizar grano'); END IF;
 SELECT COUNT(*) INTO v_n FROM (SELECT CODIGO_TRANSACCION FROM HECHOS_VENTAS GROUP BY CODIGO_TRANSACCION HAVING COUNT(DISTINCT ID_TRANSACCION_OLTP)>1 OR COUNT(DISTINCT SK_CLIENTE)>1 OR COUNT(DISTINCT SK_CANAL)>1 OR COUNT(DISTINCT SK_FECHA)>1);
 IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20052,'Transaccion con cliente/canal/fecha inconsistentes'); END IF;
 DBMS_MVIEW.REFRESH(v_esquema||'.MV_VENTAS_MENSUALES,'||v_esquema||'.MV_TOP_PRODUCTOS,'||v_esquema||'.MV_FRECUENCIA_CLIENTES,'||v_esquema||'.MV_UTILIDAD_POR_CATEGORIA,'||v_esquema||'.MV_PROMOCIONES_USADAS',method=>'CCCCC',atomic_refresh=>TRUE);
END;
