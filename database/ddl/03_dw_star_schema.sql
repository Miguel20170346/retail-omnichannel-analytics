-- HECHOS_VENTAS --------------------------------------------------------
CREATE TABLE HECHOS_VENTAS (
  ID_HECHO                 NUMBER GENERATED ALWAYS AS IDENTITY,
  SK_FECHA                 NUMBER(8)     NOT NULL,
  SK_CLIENTE               NUMBER        NOT NULL,
  SK_PRODUCTO              NUMBER        NOT NULL,
  SK_CANAL                 NUMBER        NOT NULL,
  SK_EMPLEADO              NUMBER        NOT NULL,
  SK_PROMOCION             NUMBER        NOT NULL,
  SK_METODO_PAGO           NUMBER        NOT NULL,
  -- Dimensiones degeneradas / trazabilidad
  CODIGO_TRANSACCION       VARCHAR2(40)  NOT NULL,
  ID_TRANSACCION_OLTP      NUMBER        NOT NULL,
  ID_DETALLE_OLTP          NUMBER        NOT NULL,
  FECHA_HORA_TRANSACCION   TIMESTAMP     NOT NULL,
  MONEDA_ORIGEN            VARCHAR2(3)   NOT NULL,
  TASA_USD                 NUMBER(18,6)  NOT NULL,
  -- Medidas en moneda origen
  CANTIDAD                 NUMBER(10)    NOT NULL,
  PRECIO_UNITARIO_ORIGEN   NUMBER(18,2)  NOT NULL,
  DESCUENTO_ORIGEN         NUMBER(18,2)  NOT NULL,
  IMPUESTO_ORIGEN          NUMBER(18,2)  NOT NULL,
  TOTAL_LINEA_ORIGEN       NUMBER(18,2)  NOT NULL,   -- cant*precio - desc + imp
  -- Medidas en USD
  MONTO_BRUTO_USD          NUMBER(18,2)  NOT NULL,   -- cant*precio
  DESCUENTO_USD            NUMBER(18,2)  NOT NULL,
  MONTO_NETO_USD           NUMBER(18,2)  NOT NULL,   -- bruto - descuento (base imponible)
  IMPUESTO_USD             NUMBER(18,2)  NOT NULL,
  TOTAL_LINEA_USD          NUMBER(18,2)  NOT NULL,   -- neto + impuesto
  COSTO_TOTAL_USD          NUMBER(18,2)  NOT NULL,   -- cant * costo unitario
  MARGEN_BRUTO_USD         NUMBER(18,2)  NOT NULL,   -- neto - costo
  FLAG_PROMOCION           CHAR(1)       NOT NULL,
  -- Auditoria
  ID_EJECUCION             NUMBER        NOT NULL,
  FECHA_CARGA              TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_HECHOS_VENTAS PRIMARY KEY (ID_HECHO),
  CONSTRAINT UQ_HECHOS_VENTAS_DET UNIQUE (ID_DETALLE_OLTP),          -- evita duplicar cargas
  CONSTRAINT FK_HV_FECHA     FOREIGN KEY (SK_FECHA)       REFERENCES DIM_FECHA (SK_FECHA),
  CONSTRAINT FK_HV_CLIENTE   FOREIGN KEY (SK_CLIENTE)     REFERENCES DIM_CLIENTE (SK_CLIENTE),
  CONSTRAINT FK_HV_PRODUCTO  FOREIGN KEY (SK_PRODUCTO)    REFERENCES DIM_PRODUCTO (SK_PRODUCTO),
  CONSTRAINT FK_HV_CANAL     FOREIGN KEY (SK_CANAL)       REFERENCES DIM_CANAL (SK_CANAL),
  CONSTRAINT FK_HV_EMPLEADO  FOREIGN KEY (SK_EMPLEADO)    REFERENCES DIM_EMPLEADO (SK_EMPLEADO),
  CONSTRAINT FK_HV_PROMOCION FOREIGN KEY (SK_PROMOCION)   REFERENCES DIM_PROMOCION (SK_PROMOCION),
  CONSTRAINT FK_HV_METODO    FOREIGN KEY (SK_METODO_PAGO) REFERENCES DIM_METODO_PAGO (SK_METODO_PAGO),
  CONSTRAINT FK_HV_EJECUCION FOREIGN KEY (ID_EJECUCION)   REFERENCES AUDITORIA_ETL_VENTAS (ID_EJECUCION),
  CONSTRAINT CK_HV_CANTIDAD  CHECK (CANTIDAD > 0),
  CONSTRAINT CK_HV_FLAG      CHECK (FLAG_PROMOCION IN ('S','N'))
);

CREATE INDEX IX_HV_FECHA    ON HECHOS_VENTAS (SK_FECHA);
CREATE INDEX IX_HV_CLIENTE  ON HECHOS_VENTAS (SK_CLIENTE);
CREATE INDEX IX_HV_PRODUCTO ON HECHOS_VENTAS (SK_PRODUCTO);
CREATE INDEX IX_HV_CANAL    ON HECHOS_VENTAS (SK_CANAL);
CREATE INDEX IX_HV_TRX      ON HECHOS_VENTAS (ID_TRANSACCION_OLTP);

