-- GRANO DE HECHOS_VENTAS: una fila = un producto vendido dentro de una
-- transaccion (equivale a una fila de TRX_DETALLE valida).
-- Claves sustitutas (SK_*) en todas las dimensiones; la clave del OLTP
-- se conserva como clave natural para el MERGE incremental.
-- Dimensiones tipo 1 (se sobrescriben). SCD2 queda como mejora futura.
-- Todas las medidas monetarias del hecho se guardan en moneda origen y
-- en USD para que Power BI sume siempre en USD.
-- =====================================================================
SET DEFINE OFF

-- DIM_FECHA (SK = YYYYMMDD) -------------------------------------------
CREATE TABLE DIM_FECHA (
  SK_FECHA        NUMBER(8)    NOT NULL,
  FECHA           DATE         NOT NULL,
  ANIO            NUMBER(4)    NOT NULL,
  TRIMESTRE       NUMBER(1)    NOT NULL,
  MES             NUMBER(2)    NOT NULL,
  NOMBRE_MES      VARCHAR2(20) NOT NULL,
  DIA             NUMBER(2)    NOT NULL,
  DIA_SEMANA      NUMBER(1)    NOT NULL,   -- 1 = lunes
  NOMBRE_DIA      VARCHAR2(20) NOT NULL,
  SEMANA_ANIO     NUMBER(2)    NOT NULL,
  ES_FIN_SEMANA   CHAR(1)      NOT NULL,
  CONSTRAINT PK_DIM_FECHA PRIMARY KEY (SK_FECHA),
  CONSTRAINT UQ_DIM_FECHA UNIQUE (FECHA)
);

INSERT INTO DIM_FECHA
SELECT TO_NUMBER(TO_CHAR(f, 'YYYYMMDD')),
       f,
       EXTRACT(YEAR FROM f),
       TO_NUMBER(TO_CHAR(f, 'Q')),
       EXTRACT(MONTH FROM f),
       DECODE(EXTRACT(MONTH FROM f), 1,'Enero',2,'Febrero',3,'Marzo',4,'Abril',5,'Mayo',6,'Junio',
              7,'Julio',8,'Agosto',9,'Septiembre',10,'Octubre',11,'Noviembre','Diciembre'),
       EXTRACT(DAY FROM f),
       TRUNC(f) - TRUNC(f, 'IW') + 1,
       DECODE(TRUNC(f) - TRUNC(f, 'IW') + 1, 1,'Lunes',2,'Martes',3,'Miercoles',4,'Jueves',
              5,'Viernes',6,'Sabado','Domingo'),
       TO_NUMBER(TO_CHAR(f, 'IW')),
       CASE WHEN TRUNC(f) - TRUNC(f, 'IW') + 1 >= 6 THEN 'S' ELSE 'N' END
FROM (SELECT DATE '2025-01-01' + LEVEL - 1 AS f FROM DUAL
      CONNECT BY LEVEL <= DATE '2027-12-31' - DATE '2025-01-01' + 1);
COMMIT;

