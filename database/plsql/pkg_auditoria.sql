SET DEFINE OFF

CREATE TABLE AUDITORIA_ETL_VENTAS (
  ID_EJECUCION              NUMBER GENERATED ALWAYS AS IDENTITY,
  PROCESO                   VARCHAR2(60)  NOT NULL,
  FECHA_INICIO              TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  FECHA_FIN                 TIMESTAMP,
  DURACION_SEGUNDOS         NUMBER(12,3),
  REGISTROS_EXTRAIDOS       NUMBER DEFAULT 0,
  REGISTROS_VALIDOS         NUMBER DEFAULT 0,
  REGISTROS_RECHAZADOS      NUMBER DEFAULT 0,
  REGISTROS_CARGADOS        NUMBER DEFAULT 0,
  TRANSACCIONES_EXTRAIDAS   NUMBER DEFAULT 0,
  TRANSACCIONES_CARGADAS    NUMBER DEFAULT 0,
  TRANSACCIONES_RECHAZADAS  NUMBER DEFAULT 0,
  ADVERTENCIAS              NUMBER DEFAULT 0,
  MONTO_CARGADO_USD         NUMBER(18,2) DEFAULT 0,
  FACTURAS_GENERADAS        NUMBER DEFAULT 0,
  HASH_LOTE                 VARCHAR2(64),
  ESTADO                    VARCHAR2(20) DEFAULT 'EN_PROCESO' NOT NULL,
  MENSAJE                   VARCHAR2(4000),
  USUARIO_EJECUCION         VARCHAR2(128) DEFAULT USER,
  CONSTRAINT PK_AUDITORIA_ETL PRIMARY KEY (ID_EJECUCION),
  CONSTRAINT CK_AUDITORIA_ETL_EST CHECK (ESTADO IN ('EN_PROCESO','EXITOSO','CON_RECHAZOS','FALLIDO'))
);

CREATE TABLE ERRORES_ETL_VENTAS (
  ID_ERROR             NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_EJECUCION         NUMBER        NOT NULL,
  ID_TRANSACCION_OLTP  NUMBER,
  ID_DETALLE_OLTP      NUMBER,
  CODIGO_REGLA         VARCHAR2(10)  NOT NULL,
  SEVERIDAD            VARCHAR2(12)  NOT NULL,
  DESCRIPCION          VARCHAR2(500) NOT NULL,
  VALOR_DETECTADO      VARCHAR2(500),
  HASH_REGISTRO        VARCHAR2(64),
  ESTADO_ERROR         VARCHAR2(12)  DEFAULT 'ABIERTO' NOT NULL,
  FECHA_REGISTRO       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_ERRORES_ETL PRIMARY KEY (ID_ERROR),
  CONSTRAINT FK_ERRORES_ETL_EJEC FOREIGN KEY (ID_EJECUCION) REFERENCES AUDITORIA_ETL_VENTAS (ID_EJECUCION),
  CONSTRAINT CK_ERRORES_ETL_SEV CHECK (SEVERIDAD IN ('CRITICO','ADVERTENCIA')),
  CONSTRAINT CK_ERRORES_ETL_EST CHECK (ESTADO_ERROR IN ('ABIERTO','CORREGIDO','DESCARTADO'))
);

CREATE INDEX IX_ERRORES_ETL_TRX  ON ERRORES_ETL_VENTAS (ID_TRANSACCION_OLTP);
CREATE INDEX IX_ERRORES_ETL_EJEC ON ERRORES_ETL_VENTAS (ID_EJECUCION);

CREATE OR REPLACE PACKAGE PKG_AUDITORIA AS
  FUNCTION  FN_INICIAR (p_proceso VARCHAR2) RETURN NUMBER;
  PROCEDURE PR_FINALIZAR (p_id_ejecucion NUMBER, p_mensaje VARCHAR2 DEFAULT NULL);
  PROCEDURE PR_FALLO (p_id_ejecucion NUMBER, p_mensaje VARCHAR2);
  -- Marca los errores criticos de una transaccion como corregidos para
  -- que la siguiente ejecucion del ETL vuelva a intentar cargarla.
  PROCEDURE PR_MARCAR_CORREGIDO (p_id_transaccion NUMBER);
END PKG_AUDITORIA;
/

CREATE OR REPLACE PACKAGE BODY PKG_AUDITORIA AS

  FUNCTION FN_INICIAR (p_proceso VARCHAR2) RETURN NUMBER IS
    PRAGMA AUTONOMOUS_TRANSACTION;
    v_id NUMBER;
  BEGIN
    INSERT INTO AUDITORIA_ETL_VENTAS (PROCESO) VALUES (p_proceso)
    RETURNING ID_EJECUCION INTO v_id;
    COMMIT;
    RETURN v_id;
  END FN_INICIAR;

  -- Calcula totales a partir de lo que realmente quedo registrado
  PROCEDURE PR_FINALIZAR (p_id_ejecucion NUMBER, p_mensaje VARCHAR2 DEFAULT NULL) IS
    v_rech  NUMBER;
  BEGIN
    UPDATE AUDITORIA_ETL_VENTAS a
       SET FECHA_FIN = SYSTIMESTAMP,
           DURACION_SEGUNDOS = EXTRACT(DAY FROM (SYSTIMESTAMP - a.FECHA_INICIO)) * 86400
                             + EXTRACT(HOUR FROM (SYSTIMESTAMP - a.FECHA_INICIO)) * 3600
                             + EXTRACT(MINUTE FROM (SYSTIMESTAMP - a.FECHA_INICIO)) * 60
                             + EXTRACT(SECOND FROM (SYSTIMESTAMP - a.FECHA_INICIO)),
           ADVERTENCIAS = (SELECT COUNT(*) FROM ERRORES_ETL_VENTAS e
                            WHERE e.ID_EJECUCION = a.ID_EJECUCION AND e.SEVERIDAD = 'ADVERTENCIA'),
           MENSAJE = NVL(p_mensaje, a.MENSAJE)
     WHERE ID_EJECUCION = p_id_ejecucion
     RETURNING TRANSACCIONES_RECHAZADAS INTO v_rech;

    UPDATE AUDITORIA_ETL_VENTAS
       SET ESTADO = CASE WHEN v_rech > 0 THEN 'CON_RECHAZOS' ELSE 'EXITOSO' END
     WHERE ID_EJECUCION = p_id_ejecucion;
    COMMIT;
  END PR_FINALIZAR;

  PROCEDURE PR_FALLO (p_id_ejecucion NUMBER, p_mensaje VARCHAR2) IS
    PRAGMA AUTONOMOUS_TRANSACTION;
  BEGIN
    UPDATE AUDITORIA_ETL_VENTAS
       SET ESTADO = 'FALLIDO', FECHA_FIN = SYSTIMESTAMP, MENSAJE = SUBSTR(p_mensaje, 1, 4000)
     WHERE ID_EJECUCION = p_id_ejecucion;
    COMMIT;
  END PR_FALLO;

  PROCEDURE PR_MARCAR_CORREGIDO (p_id_transaccion NUMBER) IS
  BEGIN
    UPDATE ERRORES_ETL_VENTAS
       SET ESTADO_ERROR = 'CORREGIDO'
     WHERE ID_TRANSACCION_OLTP = p_id_transaccion AND ESTADO_ERROR = 'ABIERTO';
    COMMIT;
  END PR_MARCAR_CORREGIDO;

END PKG_AUDITORIA;
