-- Flujo de PR_EJECUTAR_ETL (una sola llamada hace todo):
--   1. Inicia auditoria           (PKG_AUDITORIA.FN_INICIAR)
--   2. Extrae OLTP -> Staging     (solo ventas Pagada/Facturada nuevas)
--   3. Valida calidad             (PKG_CALIDAD.PR_VALIDAR)
--   4. Carga dimensiones          (MERGE, tipo 1)
--   5. Carga hechos               (solo filas VALIDO, convertidas a USD)
--   6. Refresca las 5 MVs
--   7. Genera facturas JSON       (solo transacciones nuevas del DW)
--   8. Cierra auditoria           (tiempos, conteos, hash del lote)
-- CARGA INCREMENTAL: una venta se extrae si aun no esta en HECHOS_VENTAS
-- y no tiene errores criticos ABIERTOS. Si se corrige un dato en el
-- OLTP, se ejecuta PKG_AUDITORIA.PR_MARCAR_CORREGIDO(id) y la siguiente
-- corrida la vuelve a intentar.
-- =====================================================================
SET DEFINE OFF

CREATE OR REPLACE PACKAGE PKG_ETL_VENTAS AS
  PROCEDURE PR_EXTRAER (p_id_ejecucion NUMBER);
  PROCEDURE PR_CARGAR_DIMENSIONES;
  PROCEDURE PR_CARGAR_HECHOS (p_id_ejecucion NUMBER);
  PROCEDURE PR_REFRESCAR_MVS;
  PROCEDURE PR_EJECUTAR_ETL;
END PKG_ETL_VENTAS;
/

CREATE OR REPLACE PACKAGE BODY PKG_ETL_VENTAS AS

  PROCEDURE PR_EXTRAER (p_id_ejecucion NUMBER) IS
  BEGIN
    DELETE FROM STG_VENTAS;
    DELETE FROM STG_CLIENTES;
    DELETE FROM STG_PRODUCTOS;
    DELETE FROM STG_EMPLEADOS;
    DELETE FROM STG_PROMOCIONES;

    INSERT INTO STG_CLIENTES
    SELECT c.ID_CLIENTE, c.NOMBRE, c.EMAIL, c.SEGMENTO,
           c.ID_PAIS, p.CODIGO_PAIS, p.NOMBRE_PAIS,
           c.ID_DEPARTAMENTO, d.ID_PAIS, d.NOMBRE_DEPARTAMENTO,
           c.ID_ZONA, z.ID_PAIS, z.NOMBRE_ZONA,
           c.FECHA_REGISTRO, c.ACTIVO
      FROM TRX_CLIENTES c
      JOIN TRX_PAISES p        ON p.ID_PAIS = c.ID_PAIS
      JOIN TRX_DEPARTAMENTOS d ON d.ID_DEPARTAMENTO = c.ID_DEPARTAMENTO
      JOIN TRX_ZONAS z         ON z.ID_ZONA = c.ID_ZONA;

    INSERT INTO STG_PRODUCTOS
    SELECT pr.ID_PRODUCTO, pr.NOMBRE_PRODUCTO, cat.NOMBRE_CATEGORIA, pad.NOMBRE_CATEGORIA,
           m.NOMBRE_MARCA, pv.NOMBRE_PROVEEDOR, pr.PRECIO_BASE, pr.COSTO_UNITARIO_USD,
           pr.FECHA_INICIO_PRECIO, pr.FECHA_FIN_PRECIO
      FROM TRX_PRODUCTOS pr
      JOIN TRX_CATEGORIAS_PRODUCTO cat ON cat.ID_CATEGORIA = pr.ID_CATEGORIA
      LEFT JOIN TRX_CATEGORIAS_PRODUCTO pad ON pad.ID_CATEGORIA = cat.ID_CATEGORIA_PADRE
      JOIN TRX_MARCAS m       ON m.ID_MARCA = pr.ID_MARCA
      JOIN TRX_PROVEEDORES pv ON pv.ID_PROVEEDOR = pr.ID_PROVEEDOR;

    INSERT INTO STG_EMPLEADOS
    SELECT e.ID_EMPLEADO, e.NOMBRE, e.CARGO, s.CODIGO_SUCURSAL, s.NOMBRE_SUCURSAL,
           d.NOMBRE_DEPARTAMENTO, p.NOMBRE_PAIS, e.ACTIVO
      FROM TRX_EMPLEADOS e
      JOIN TRX_SUCURSALES s    ON s.ID_SUCURSAL = e.ID_SUCURSAL
      JOIN TRX_DEPARTAMENTOS d ON d.ID_DEPARTAMENTO = s.ID_DEPARTAMENTO
      JOIN TRX_PAISES p        ON p.ID_PAIS = d.ID_PAIS;

    INSERT INTO STG_PROMOCIONES
    SELECT ID_PROMOCION, ID_PRODUCTO, TIPO, VALOR, FECHA_INICIO, FECHA_FIN, DESCRIPCION, ACTIVO
      FROM TRX_PROMOCIONES;

    INSERT INTO STG_VENTAS (ID_EJECUCION, ID_TRANSACCION, ID_DETALLE, FECHA_TRANSACCION, CODIGO_CANAL,
                            ID_CLIENTE, ID_EMPLEADO, NOMBRE_METODO_PAGO, NOMBRE_ESTADO, MONEDA_ORIGEN,
                            TOTAL_CABECERA, ID_PRODUCTO, ID_PROMOCION, CANTIDAD, PRECIO_UNITARIO,
                            DESCUENTO, IMPUESTO)
    SELECT p_id_ejecucion, v.ID_TRANSACCION, d.ID_DETALLE, v.FECHA_TRANSACCION, cn.CODIGO_CANAL,
           v.ID_CLIENTE, v.ID_EMPLEADO, mp.NOMBRE_METODO, ev.NOMBRE_ESTADO, v.MONEDA_ORIGEN,
           v.TOTAL, d.ID_PRODUCTO, d.ID_PROMOCION, d.CANTIDAD, d.PRECIO_UNITARIO,
           d.DESCUENTO, d.IMPUESTO
      FROM TRX_VENTAS v
      JOIN TRX_DETALLE d        ON d.ID_TRANSACCION = v.ID_TRANSACCION AND d.ACTIVO = 'S'
      JOIN TRX_CANALES cn       ON cn.ID_CANAL = v.ID_CANAL
      JOIN TRX_METODOS_PAGO mp  ON mp.ID_METODO_PAGO = v.ID_METODO_PAGO
      JOIN TRX_ESTADOS_VENTA ev ON ev.ID_ESTADO_VENTA = v.ID_ESTADO_VENTA
     WHERE v.ACTIVO = 'S'
       AND ev.NOMBRE_ESTADO IN ('Pagada','Facturada')
       AND NOT EXISTS (SELECT 1 FROM HECHOS_VENTAS h WHERE h.ID_TRANSACCION_OLTP = v.ID_TRANSACCION)
       AND NOT EXISTS (SELECT 1 FROM ERRORES_ETL_VENTAS e
                        WHERE e.ID_TRANSACCION_OLTP = v.ID_TRANSACCION
                          AND e.SEVERIDAD = 'CRITICO' AND e.ESTADO_ERROR = 'ABIERTO');

    UPDATE AUDITORIA_ETL_VENTAS a
       SET REGISTROS_EXTRAIDOS     = (SELECT COUNT(*) FROM STG_VENTAS WHERE ID_EJECUCION = p_id_ejecucion),
           TRANSACCIONES_EXTRAIDAS = (SELECT COUNT(DISTINCT ID_TRANSACCION) FROM STG_VENTAS WHERE ID_EJECUCION = p_id_ejecucion)
     WHERE a.ID_EJECUCION = p_id_ejecucion;
  END PR_EXTRAER;

  PROCEDURE PR_CARGAR_DIMENSIONES IS
  BEGIN
    MERGE INTO DIM_CLIENTE d
    USING STG_CLIENTES s ON (d.ID_CLIENTE_OLTP = s.ID_CLIENTE)
    WHEN MATCHED THEN UPDATE SET
      d.NOMBRE = s.NOMBRE, d.EMAIL = s.EMAIL, d.SEGMENTO = s.SEGMENTO, d.PAIS = s.NOMBRE_PAIS,
      d.CODIGO_PAIS = s.CODIGO_PAIS, d.DEPARTAMENTO = s.NOMBRE_DEPARTAMENTO, d.ZONA = s.NOMBRE_ZONA,
      d.FECHA_REGISTRO = s.FECHA_REGISTRO, d.FECHA_ACTUALIZACION = SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT
      (ID_CLIENTE_OLTP, NOMBRE, EMAIL, SEGMENTO, PAIS, CODIGO_PAIS, DEPARTAMENTO, ZONA, FECHA_REGISTRO)
      VALUES (s.ID_CLIENTE, s.NOMBRE, s.EMAIL, s.SEGMENTO, s.NOMBRE_PAIS, s.CODIGO_PAIS,
              s.NOMBRE_DEPARTAMENTO, s.NOMBRE_ZONA, s.FECHA_REGISTRO);

    MERGE INTO DIM_PRODUCTO d
    USING STG_PRODUCTOS s ON (d.ID_PRODUCTO_OLTP = s.ID_PRODUCTO)
    WHEN MATCHED THEN UPDATE SET
      d.NOMBRE_PRODUCTO = s.NOMBRE_PRODUCTO, d.CATEGORIA = s.NOMBRE_CATEGORIA,
      d.CATEGORIA_PADRE = s.CATEGORIA_PADRE, d.MARCA = s.NOMBRE_MARCA, d.PROVEEDOR = s.NOMBRE_PROVEEDOR,
      d.PRECIO_BASE_USD = s.PRECIO_BASE, d.COSTO_UNITARIO_USD = s.COSTO_UNITARIO_USD,
      d.FECHA_ACTUALIZACION = SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT
      (ID_PRODUCTO_OLTP, NOMBRE_PRODUCTO, CATEGORIA, CATEGORIA_PADRE, MARCA, PROVEEDOR, PRECIO_BASE_USD, COSTO_UNITARIO_USD)
      VALUES (s.ID_PRODUCTO, s.NOMBRE_PRODUCTO, s.NOMBRE_CATEGORIA, s.CATEGORIA_PADRE, s.NOMBRE_MARCA,
              s.NOMBRE_PROVEEDOR, s.PRECIO_BASE, s.COSTO_UNITARIO_USD);

    MERGE INTO DIM_EMPLEADO d
    USING STG_EMPLEADOS s ON (d.ID_EMPLEADO_OLTP = s.ID_EMPLEADO)
    WHEN MATCHED THEN UPDATE SET
      d.NOMBRE = s.NOMBRE, d.CARGO = s.CARGO, d.CODIGO_SUCURSAL = s.CODIGO_SUCURSAL,
      d.SUCURSAL = s.NOMBRE_SUCURSAL, d.DEPARTAMENTO_SUCURSAL = s.NOMBRE_DEPARTAMENTO,
      d.PAIS_SUCURSAL = s.NOMBRE_PAIS, d.FECHA_ACTUALIZACION = SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT
      (ID_EMPLEADO_OLTP, NOMBRE, CARGO, CODIGO_SUCURSAL, SUCURSAL, DEPARTAMENTO_SUCURSAL, PAIS_SUCURSAL)
      VALUES (s.ID_EMPLEADO, s.NOMBRE, s.CARGO, s.CODIGO_SUCURSAL, s.NOMBRE_SUCURSAL,
              s.NOMBRE_DEPARTAMENTO, s.NOMBRE_PAIS);

    MERGE INTO DIM_PROMOCION d
    USING STG_PROMOCIONES s ON (d.ID_PROMOCION_OLTP = s.ID_PROMOCION)
    WHEN MATCHED THEN UPDATE SET
      d.TIPO = s.TIPO, d.VALOR = s.VALOR, d.DESCRIPCION = NVL(s.DESCRIPCION, 'Promocion ' || s.ID_PROMOCION),
      d.FECHA_INICIO = s.FECHA_INICIO, d.FECHA_FIN = s.FECHA_FIN, d.FECHA_ACTUALIZACION = SYSTIMESTAMP
    WHEN NOT MATCHED THEN INSERT
      (ID_PROMOCION_OLTP, TIPO, VALOR, DESCRIPCION, FECHA_INICIO, FECHA_FIN)
      VALUES (s.ID_PROMOCION, s.TIPO, s.VALOR, NVL(s.DESCRIPCION, 'Promocion ' || s.ID_PROMOCION),
              s.FECHA_INICIO, s.FECHA_FIN);

    MERGE INTO DIM_CANAL d
    USING TRX_CANALES s ON (d.CODIGO_CANAL = s.CODIGO_CANAL)
    WHEN MATCHED THEN UPDATE SET d.NOMBRE_CANAL = s.NOMBRE_CANAL
    WHEN NOT MATCHED THEN INSERT (CODIGO_CANAL, NOMBRE_CANAL) VALUES (s.CODIGO_CANAL, s.NOMBRE_CANAL);

    MERGE INTO DIM_METODO_PAGO d
    USING TRX_METODOS_PAGO s ON (d.NOMBRE_METODO = s.NOMBRE_METODO)
    WHEN NOT MATCHED THEN INSERT (NOMBRE_METODO) VALUES (s.NOMBRE_METODO);
  END PR_CARGAR_DIMENSIONES;

  PROCEDURE PR_CARGAR_HECHOS (p_id_ejecucion NUMBER) IS
    v_hash VARCHAR2(64);
  BEGIN
    INSERT INTO HECHOS_VENTAS (
      SK_FECHA, SK_CLIENTE, SK_PRODUCTO, SK_CANAL, SK_EMPLEADO, SK_PROMOCION, SK_METODO_PAGO,
      CODIGO_TRANSACCION, ID_TRANSACCION_OLTP, ID_DETALLE_OLTP, FECHA_HORA_TRANSACCION,
      MONEDA_ORIGEN, TASA_USD, CANTIDAD, PRECIO_UNITARIO_ORIGEN, DESCUENTO_ORIGEN, IMPUESTO_ORIGEN,
      TOTAL_LINEA_ORIGEN, MONTO_BRUTO_USD, DESCUENTO_USD, MONTO_NETO_USD, IMPUESTO_USD,
      TOTAL_LINEA_USD, COSTO_TOTAL_USD, MARGEN_BRUTO_USD, FLAG_PROMOCION, ID_EJECUCION)
    SELECT TO_NUMBER(TO_CHAR(x.FECHA_TRANSACCION, 'YYYYMMDD')),
           x.SK_CLIENTE, x.SK_PRODUCTO, x.SK_CANAL, x.SK_EMPLEADO, x.SK_PROMOCION, x.SK_METODO_PAGO,
           x.CODIGO_TRANSACCION, x.ID_TRANSACCION, x.ID_DETALLE, x.FECHA_TRANSACCION,
           x.MONEDA_ORIGEN, x.TASA_USD, x.CANTIDAD, x.PRECIO_UNITARIO, x.DESCUENTO, x.IMPUESTO,
           x.CANTIDAD * x.PRECIO_UNITARIO - x.DESCUENTO + x.IMPUESTO,
           x.BRUTO_USD, x.DESC_USD, x.BRUTO_USD - x.DESC_USD, x.IMP_USD,
           x.BRUTO_USD - x.DESC_USD + x.IMP_USD,
           x.COSTO_USD, x.BRUTO_USD - x.DESC_USD - x.COSTO_USD,
           CASE WHEN x.ID_PROMOCION IS NULL THEN 'N' ELSE 'S' END,
           p_id_ejecucion
      FROM (SELECT s.*,
                   dc.SK_CLIENTE, dp.SK_PRODUCTO, dca.SK_CANAL, de.SK_EMPLEADO,
                   NVL(dpr.SK_PROMOCION, 0) AS SK_PROMOCION, dm.SK_METODO_PAGO,
                   ROUND(s.CANTIDAD * s.PRECIO_UNITARIO * s.TASA_USD, 2)    AS BRUTO_USD,
                   ROUND(s.DESCUENTO * s.TASA_USD, 2)                       AS DESC_USD,
                   ROUND(s.IMPUESTO * s.TASA_USD, 2)                        AS IMP_USD,
                   ROUND(s.CANTIDAD * NVL(dp.COSTO_UNITARIO_USD, 0), 2)     AS COSTO_USD
              FROM STG_VENTAS s
              JOIN DIM_CLIENTE dc     ON dc.ID_CLIENTE_OLTP = s.ID_CLIENTE
              JOIN DIM_PRODUCTO dp    ON dp.ID_PRODUCTO_OLTP = s.ID_PRODUCTO
              JOIN DIM_CANAL dca      ON dca.CODIGO_CANAL = s.CODIGO_CANAL
              JOIN DIM_EMPLEADO de    ON de.ID_EMPLEADO_OLTP = s.ID_EMPLEADO
              JOIN DIM_METODO_PAGO dm ON dm.NOMBRE_METODO = s.NOMBRE_METODO_PAGO
              LEFT JOIN DIM_PROMOCION dpr ON dpr.ID_PROMOCION_OLTP = s.ID_PROMOCION
             WHERE s.ID_EJECUCION = p_id_ejecucion
               AND s.ESTADO_VALIDACION = 'VALIDO') x;

    -- Hash de control del lote: cualquiera puede recalcularlo para
    -- comprobar que lo cargado no fue modificado.
    SELECT LOWER(RAWTOHEX(STANDARD_HASH(
             p_id_ejecucion || '|' || COUNT(*) || '|' ||
             TO_CHAR(NVL(SUM(TOTAL_LINEA_USD), 0), 'FM999999999999990.00') || '|' ||
             MIN(ID_DETALLE_OLTP) || '|' || MAX(ID_DETALLE_OLTP), 'SHA256')))
      INTO v_hash
      FROM HECHOS_VENTAS WHERE ID_EJECUCION = p_id_ejecucion;

    UPDATE AUDITORIA_ETL_VENTAS a
       SET REGISTROS_VALIDOS    = (SELECT COUNT(*) FROM STG_VENTAS WHERE ID_EJECUCION = p_id_ejecucion AND ESTADO_VALIDACION = 'VALIDO'),
           REGISTROS_RECHAZADOS = (SELECT COUNT(*) FROM STG_VENTAS WHERE ID_EJECUCION = p_id_ejecucion AND ESTADO_VALIDACION = 'RECHAZADO'),
           TRANSACCIONES_RECHAZADAS = (SELECT COUNT(DISTINCT NVL(ID_TRANSACCION, -1)) FROM STG_VENTAS
                                        WHERE ID_EJECUCION = p_id_ejecucion AND ESTADO_VALIDACION = 'RECHAZADO'),
           REGISTROS_CARGADOS     = (SELECT COUNT(*) FROM HECHOS_VENTAS WHERE ID_EJECUCION = p_id_ejecucion),
           TRANSACCIONES_CARGADAS = (SELECT COUNT(DISTINCT ID_TRANSACCION_OLTP) FROM HECHOS_VENTAS WHERE ID_EJECUCION = p_id_ejecucion),
           MONTO_CARGADO_USD      = (SELECT NVL(SUM(TOTAL_LINEA_USD), 0) FROM HECHOS_VENTAS WHERE ID_EJECUCION = p_id_ejecucion),
           HASH_LOTE = v_hash
     WHERE a.ID_EJECUCION = p_id_ejecucion;
  END PR_CARGAR_HECHOS;

  PROCEDURE PR_REFRESCAR_MVS IS
  BEGIN
    PR_REFRESCAR_MVS_KEYLA;
  END PR_REFRESCAR_MVS;

  PROCEDURE PR_EJECUTAR_ETL IS
    v_id       NUMBER;
    v_facturas NUMBER;
    r          AUDITORIA_ETL_VENTAS%ROWTYPE;
  BEGIN
    v_id := PKG_AUDITORIA.FN_INICIAR('ETL_VENTAS');

    PR_EXTRAER(v_id);
    PKG_CALIDAD.PR_VALIDAR(v_id);
    PR_CARGAR_DIMENSIONES;
    PR_CARGAR_HECHOS(v_id);
    COMMIT;                       -- staging + errores + DW quedan consistentes

    PR_REFRESCAR_MVS;             -- DBMS_MVIEW hace su propio COMMIT
    PR_GENERAR_FACTURAS_JSON(v_facturas);
    UPDATE AUDITORIA_ETL_VENTAS SET FACTURAS_GENERADAS = v_facturas WHERE ID_EJECUCION = v_id;

    PKG_AUDITORIA.PR_FINALIZAR(v_id, 'ETL completado');   -- hace COMMIT

    SELECT * INTO r FROM AUDITORIA_ETL_VENTAS WHERE ID_EJECUCION = v_id;
    DBMS_OUTPUT.PUT_LINE('Ejecucion ' || v_id || ' -> ' || r.ESTADO);
    DBMS_OUTPUT.PUT_LINE('  Transacciones extraidas : ' || r.TRANSACCIONES_EXTRAIDAS);
    DBMS_OUTPUT.PUT_LINE('  Transacciones cargadas  : ' || r.TRANSACCIONES_CARGADAS);
    DBMS_OUTPUT.PUT_LINE('  Transacciones rechazadas: ' || r.TRANSACCIONES_RECHAZADAS);
    DBMS_OUTPUT.PUT_LINE('  Lineas cargadas al DW   : ' || r.REGISTROS_CARGADOS);
    DBMS_OUTPUT.PUT_LINE('  Advertencias            : ' || r.ADVERTENCIAS);
    DBMS_OUTPUT.PUT_LINE('  Monto cargado USD       : ' || TO_CHAR(r.MONTO_CARGADO_USD, 'FM999,999,990.00'));
    DBMS_OUTPUT.PUT_LINE('  Facturas JSON generadas : ' || r.FACTURAS_GENERADAS);
    DBMS_OUTPUT.PUT_LINE('  Duracion (s)            : ' || r.DURACION_SEGUNDOS);
    DBMS_OUTPUT.PUT_LINE('  Hash del lote           : ' || r.HASH_LOTE);
  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK;
      IF v_id IS NOT NULL THEN
        PKG_AUDITORIA.PR_FALLO(v_id, SQLERRM || ' ' || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE);
      END IF;
      RAISE;
  END PR_EJECUTAR_ETL;

END PKG_ETL_VENTAS;
